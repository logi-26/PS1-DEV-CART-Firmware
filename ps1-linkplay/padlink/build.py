"""Builds the CTR pad play driver (padlink.c + padlink_head.S) into padlink_ctr.json: the code for its gap (Time Trial's
ghost replay, 0x80026ED8), the SHA-1 of the game's original bytes there (checked before installing), the patched
words (each with the game's original, checked), the exchange area's address and the carrier's hook (pl_service).

  python build.py [SCUS_944.26]     (the game's executable; default research/ctr/disc/SCUS_944.26)
"""
import hashlib
import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TOOLS = os.environ.get("MIPS_TOOLS") or os.path.join(os.environ.get("APPDATA", ""), "mips", "mips", "bin")
CC, OBJCOPY, NM = (os.path.join(TOOLS, "mipsel-none-elf-" + t) for t in ("gcc", "objcopy", "nm"))
BUF = 0x8000D810
GAP, GAP_SIZE = 0x80026ED8, 0x960
FLAGS = ["-Os", "-G0", "-march=r3000", "-msoft-float", "-mno-abicalls", "-fno-pic", "-ffreestanding", "-fno-builtin",
         "-nostdlib", "-mno-gpopt", "-fno-toplevel-reorder"]
EXE = os.path.join(HERE, "..", "research", "ctr", "disc", "SCUS_944.26")
GUI = os.path.join(HERE, "..", "..", "gui")


def run(*args):
    r = subprocess.run(args, capture_output=True, text=True, cwd=HERE)
    if r.returncode:
        sys.exit(r.stdout + r.stderr)
    return r.stdout


def j(target):
    return 0x08000000 | ((target >> 2) & 0x03FFFFFF)


def main():
    exe = open(sys.argv[1] if len(sys.argv) > 1 else EXE, "rb").read()
    orig = lambda a, n: exe[a - 0x80010000 + 0x800:a - 0x80010000 + 0x800 + n]
    word = lambda a: int.from_bytes(orig(a, 4), "little")
    elf = os.path.join(HERE, "padlink.elf")
    run(CC, *FLAGS, "-DPL_HW", "-DPL_BUF=0x%X" % BUF, "-T", "padlink.ld", "-Wl,-e,0", "-o", elf,
        "padlink_head.S", "padlink.c")
    syms = {m.group(3): int(m.group(1), 16) for m in re.finditer(r"^([0-9a-f]+) (\w) (\w+)$", run(NM, elf), re.M)}
    binf = os.path.join(HERE, "padlink.bin")
    run(OBJCOPY, "-O", "binary", "-j", ".pl", elf, binf)
    code = open(binf, "rb").read()
    stray = os.path.join(HERE, "stray.bin")
    run(OBJCOPY, "-O", "binary", "-j", ".stray", elf, stray)
    if os.path.getsize(stray):
        sys.exit("code outside the gap (a function without IN)")
    os.remove(stray)
    if len(code) > GAP_SIZE:
        sys.exit("%d bytes, the gap has %d" % (len(code), GAP_SIZE))
    # The patched words: (address, the game's original, ours)
    patches = [
        (0x800262D0, 0x27BDFFE0, j(syms["pl_frame_stub"])),   # GAMEPAD_ProcessAnyoneVars: addiu sp,sp,-0x20
        (0x800262D4, 0xAFB00010, 0),                           #   sw s0,0x10(sp)
        (0x8003CB78, 0x24020020, j(syms["pl_load_stub"])),     # race start: addiu v0,zero,0x20
        (0x8003CB7C, 0xAC821D04, 0),                           #   sw v0,0x1D04(a0)
        (0x80078BE8, 0x240A00A0, j(syms["pl_rand"])),          # the BIOS rand stub: li t2,0xA0
        (0x80078BEC, 0x01400008, 0),                           #   jr t2
        (0x80034ED4, word(0x80034ED4), 0),                     # the frame step: negative -> 32 (a fixed step)
    ]
    for a, want, _ in patches:
        if word(a) != want:
            sys.exit("%08X is %08X, not %08X: another version of the game?" % (a, word(a), want))
    out = {"game": "SCUS_944.26", "buf": BUF, "buf_size": 0x128,
           "gap": {"adrs": GAP, "hex": code.hex(), "size": GAP_SIZE,
                   "orig_sha1": hashlib.sha1(orig(GAP, GAP_SIZE)).hexdigest()},
           "words": [{"adrs": a, "orig": o, "new": n} for a, o, n in patches],
           "service": syms["pl_service"], "frame": syms["pl_frame"]}
    with open(os.path.join(HERE, "padlink_ctr.json"), "w") as f:
        json.dump(out, f, indent=1)
    # The Manager's package (gui/data/netplay, found by the Net Play page like the link games'): the driver and what
    # the Host / Join windows offer (gui/ctr_package.py)
    sys.path.insert(0, GUI)
    import ctr_package
    pkg = dict(out, title="Crash Team Racing", discs=["SCUS_944.26"], kind="padplay",
               link_play="nothing on the console: keep the game at its main menu, the Manager starts it",
               options=ctr_package.PLAYER_OPTIONS, host_options=ctr_package.HOST_OPTIONS)
    with open(os.path.join(GUI, "data", "netplay", "crash_team_racing.json"), "w") as f:
        json.dump(pkg, f, indent=1)
    print("gui/data/netplay/crash_team_racing.json written")
    # the same for the emulator's carrier (padlink.lua)
    with open(os.path.join(HERE, "padlink_ctr.lua"), "w") as f:
        f.write("-- generated by build.py\nreturn {buf = %d, buf_size = %d, service = %d, frame = %d,\n"
                % (BUF, out["buf_size"], out["service"], out["frame"]))
        f.write("  gap = {adrs = %d, hex = '%s', first = %d},\n" % (GAP, code.hex(), word(GAP)))
        f.write("  words = {%s}}\n" % ", ".join("{adrs = %d, orig = %d, new = %d}" % w for w in patches))
    print("padlink: %d of %d bytes at %08X; pl_service %08X" % (len(code), GAP_SIZE, GAP, syms["pl_service"]))
    for a, o, n in patches:
        print("  %08X %08X -> %08X" % (a, o, n))


if __name__ == "__main__":
    main()
